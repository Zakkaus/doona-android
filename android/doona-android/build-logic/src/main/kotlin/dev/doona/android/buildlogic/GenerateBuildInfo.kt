package dev.doona.android.buildlogic

import org.gradle.api.DefaultTask
import org.gradle.api.GradleException
import org.gradle.api.file.DirectoryProperty
import org.gradle.api.file.RegularFileProperty
import org.gradle.api.tasks.CacheableTask
import org.gradle.api.tasks.InputFile
import org.gradle.api.tasks.OutputDirectory
import org.gradle.api.tasks.PathSensitive
import org.gradle.api.tasks.PathSensitivity
import org.gradle.api.tasks.TaskAction
import java.io.File

private val honkDependency = Regex("""^honk-[a-z-]+\s*=\s*\{.*git\s*=\s*"https://github\.com/daeuniverse/honk".*$""")
private val revision = Regex("""\brev\s*=\s*"([0-9a-f]{40})"""")

/**
 * Generates `dev.doona.android.engine.BuildInfo` from what the build pins, so the app never carries a hand-copied
 * copy: the daeuniverse/honk revision of doona-core's Cargo.toml and geo-pins.json's `release_date`.
 */
@CacheableTask
abstract class GenerateBuildInfo : DefaultTask() {
    @get:InputFile
    @get:PathSensitive(PathSensitivity.NONE)
    abstract val cargoToml: RegularFileProperty

    @get:InputFile
    @get:PathSensitive(PathSensitivity.NONE)
    abstract val pinsFile: RegularFileProperty

    @get:OutputDirectory
    abstract val outputDir: DirectoryProperty

    @TaskAction
    fun generate() {
        val honk = honkRevision(cargoToml.get().asFile)
        val geo = GeoPins.read(pinsFile.get().asFile).releaseDate
        val output = outputDir.get().asFile
        output.deleteRecursively()
        val file = output.resolve("dev/doona/android/engine/BuildInfo.kt")
        file.parentFile.mkdirs()
        file.writeText(
            """
            |// Generated by build-logic GenerateBuildInfo; edit crates/doona-core/Cargo.toml or geo-pins.json instead.
            |package dev.doona.android.engine
            |
            |/** What this build pins. */
            |object BuildInfo {
            |    /** The full daeuniverse/honk commit doona-core builds honk-config and honk-outbound from. */
            |    const val HONK_REVISION: String = "$honk"
            |
            |    /** The release date (yyyy-MM-dd) of the GeoIP and GeoSite data the APK carries: geo-pins.json's `release_date`. */
            |    const val GEO_SHIPPED_DATE: String = "$geo"
            |}
            |
            """.trimMargin(),
        )
    }
}

/** The one revision every daeuniverse/honk dependency of [cargoToml] pins; none, or two that differ, fail the build. */
internal fun honkRevision(cargoToml: File): String {
    val revisions = cargoToml.readLines()
        .filter { honkDependency.matches(it.trim()) }
        .map { revision.find(it)?.groupValues?.get(1) ?: throw GradleException("$cargoToml: a honk dependency without a full rev: $it") }
        .toSet()
    return revisions.singleOrNull()
        ?: throw GradleException("$cargoToml: expected one daeuniverse/honk rev, found ${revisions.ifEmpty { "none" }}")
}
