# Generates feature/nodes/NodePlaceTable.kt from doona-core's region tables.
# python3 -I tools/gen-node-places.py <repo>/crates/doona-core/src/regions <app>/feature/model/RvCity.kt <app>/feature/nodes/NodePlaceTable.kt
import re, sys
core = sys.argv[1]; model = sys.argv[2]; out = sys.argv[3]
data = open(core + '/data.rs', encoding='utf-8').read()
regions = re.findall(r'region\("([A-Z]{2})", [-0-9.]+, [-0-9.]+, "([^"]*)"\)', data)
cities_src = open(core + '/cities.rs', encoding='utf-8').read()
cities = re.findall(r'^"([A-Z]{2})" "([a-z-]+)" \([^)]*\) "([^"]*)" "([^"]*)" "([^"]*)" "([^"]*)";', cities_src, re.M)
city_enum = dict(re.findall(r'^\s+(\w+)\("([a-z-]+)", RvPlace\.', open(model, encoding='utf-8').read(), re.M))
ids = {v: k for k, v in city_enum.items()}
places = {r[0] for r in regions}
flags = re.findall(r'\("([A-Z]{2})", ', open(core + '/flags.rs', encoding='utf-8').read())


def q(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"').replace('$', '\\$') + '"'


def city_keys(en, tw, cn, cid, al):
    keys = []
    for k in [en, tw, cn, cid] + [a for a in al.split('|') if a]:
        bare = k.lstrip('?^+')
        if any(b.lstrip('?^+').lower() == bare.lower() for b in keys):
            continue
        keys.append(k)
    return keys


L = []
L.append('// Generated by android/doona-android/tools/gen-node-places.py from crates/doona-core/src/regions; do not edit.')
L.append('package dev.doona.android.feature.nodes')
L.append('')
L.append('import dev.doona.android.designsystem.rv.RvPlace')
L.append('import dev.doona.android.feature.model.RvCity')
L.append('')
L.append('/**')
L.append(" * doona-core's region aliases (`regions/data.rs`, in its priority order), `|` between keys, the ISO code first; the")
L.append(' * v2-only `!` aliases are left out, as the core leaves them out of its matcher.')
L.append(' */')
L.append('internal val NODE_PLACE_ALIASES: List<Pair<RvPlace, String>> = listOf(')
for iso, al in regions:
    keys = [iso] + [k.lstrip('~#') for k in al.split('|') if k and not k.startswith('!')]
    L.append(f'    RvPlace.{iso} to {q("|".join(keys))},')
L.append(')')
L.append('')
L.append("/** The aliases of the cities [RvCity] has (`regions/cities.rs`). A key's first character keeps the core's marker. */")
L.append('internal val NODE_CITY_ALIASES: List<Pair<RvCity, String>> = listOf(')
for iso, cid, en, tw, cn, al in cities:
    if cid in ids:
        L.append(f'    RvCity.{ids[cid]} to {q("|".join(city_keys(en, tw, cn, cid, al)))},')
L.append(')')
L.append('')
L.append("/** The core's other cities in the app's places: they place a node in its country but name no city the app draws. */")
L.append('internal val NODE_SITE_ALIASES: List<Pair<RvPlace, String>> = listOf(')
for iso, cid, en, tw, cn, al in cities:
    if cid not in ids and iso in places:
        L.append(f'    RvPlace.{iso} to {q("|".join(city_keys(en, tw, cn, cid, al)))},')
L.append(')')
L.append('')
L.append("/** The flags the core knows beyond the app's places (`regions/flags.rs`): such a flag places a node under 其他. */")
L.append('internal val NODE_FLAG_ONLY: Set<String> = setOf(')
for i in range(0, len(flags), 16):
    L.append('    ' + ' '.join(q(c) + ',' for c in flags[i:i + 16]))
L.append(')')
open(out, 'w', encoding='utf-8').write('\n'.join(L) + '\n')
print('regions', len(regions), 'cities', sum(c[1] in ids for c in cities), 'sites', sum(c[1] not in ids and c[0] in places for c in cities), 'flags', len(flags))
