"""Writes the land mask behind the prototype/rv activity header's dot map.

Usage: python -I tools/rv_land_mask.py <ne_110m_land.geojson> > app/src/debug/kotlin/dev/doona/android/prototype/rv/RvLandMask.kt
The input is Natural Earth's 1:110m land polygons (public domain), v5.1.2:
https://raw.githubusercontent.com/nvkelso/natural-earth-vector/v5.1.2/geojson/ne_110m_land.geojson
The output is an equirectangular grid of CELL-degree cells from NORTH down to SOUTH (Antarctica left out), one hex
string per band of latitude. A cell is land when at least LAND of its SAMPLES x SAMPLES points fall on land, so islands
the size of Taiwan keep a dot.
"""

import json
import sys

CELL = 2
NORTH = 84
SOUTH = -58
COLUMNS = 360 // CELL
SAMPLES = 4
LAND = 2


def crossings(rings, lat):
    """The longitudes where a polygon's edges cross a latitude, sorted: inside lies between pairs."""
    xs = []
    for ring in rings:
        for (x1, y1), (x2, y2) in zip(ring, ring[1:]):
            if (y1 <= lat < y2) or (y2 <= lat < y1):
                xs.append(x1 + (lat - y1) * (x2 - x1) / (y2 - y1))
    return sorted(xs)


def polygons(geojson):
    for feature in geojson["features"]:
        geometry = feature["geometry"]
        if geometry["type"] == "Polygon":
            yield geometry["coordinates"]
        else:
            yield from geometry["coordinates"]


def land_counts(shapes, rows):
    counts = [[0] * COLUMNS for _ in range(rows)]
    for row in range(rows):
        for sy in range(SAMPLES):
            lat = NORTH - CELL * (row + (sy + 0.5) / SAMPLES)
            hits = set()
            for rings in shapes:
                xs = crossings(rings, lat)
                for west, east in zip(xs[::2], xs[1::2]):
                    first = int((west + 180) * SAMPLES / CELL - 0.5) + 1
                    last = int((east + 180) * SAMPLES / CELL - 0.5)
                    hits.update(range(max(first, 0), min(last, COLUMNS * SAMPLES - 1) + 1))
            for sample in hits:
                counts[row][sample // SAMPLES] += 1
    return counts


def main():
    with open(sys.argv[1]) as f:
        shapes = list(polygons(json.load(f)))
    rows = (NORTH - SOUTH) // CELL
    counts = land_counts(shapes, rows)
    hex_rows = []
    for row in counts:
        bits = "".join("1" if n >= LAND else "0" for n in row)
        hex_rows.append("".join(f"{int(bits[i : i + 4], 2):x}" for i in range(0, COLUMNS, 4)))
    body = "\n".join(f'        "{r}",' for r in hex_rows)
    print(f"""package dev.doona.android.prototype.rv

// Generated by tools/rv_land_mask.py from Natural Earth 1:110m land (ne_110m_land.geojson, v5.1.2), which is in the
// public domain: https://www.naturalearthdata.com/about/terms-of-use/. Regenerate rather than edit.

/**
 * Land on an equirectangular grid of [CELL]-degree cells: [ROWS] bands of latitude from [NORTH] degrees down, each a
 * hex string of [COLUMNS] cells from 180 degrees west, the high bit of a digit first.
 */
internal object RvLandMask {{
    const val CELL = {CELL}f
    const val NORTH = {NORTH}f
    const val COLUMNS = {COLUMNS}
    const val ROWS = {rows}

    val rows = listOf(
{body}
    )
}}""")


if __name__ == "__main__":
    main()
