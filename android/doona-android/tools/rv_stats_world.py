"""Writes the world map of the prototype/rv 統計 page's 節點分佈 card.

Usage: python -I tools/rv_stats_world.py <ne_110m_admin_0_countries.geojson> > app/src/debug/res/drawable/rv_stats_world.xml
The input is Natural Earth's 1:110m Admin 0 countries (public domain), v5.1.2:
https://raw.githubusercontent.com/nvkelso/natural-earth-vector/v5.1.2/geojson/ne_110m_admin_0_countries.geojson
The output is a vector drawable with one filled path per country, named by its ISO 3166-1 alpha-2 code (ISO_A2_EH), on a
Miller cylindrical projection from NORTH down to SOUTH (Antarctica left out), SCALE viewport units per degree of
longitude. Each ring is simplified (Douglas-Peucker, TOLERANCE units) and rounded to whole units. The card draws the paths
itself in its own colours; RvStatsMap.kt projects places too small for 1:110m (Hong Kong, Singapore) with these constants.
"""

import json
import math
import sys

NORTH = 83
SOUTH = -56
SCALE = 2
TOLERANCE = 0.6
LEFT_OUT = {"AQ"}


def miller(lat):
    """Miller's y for a latitude, in degrees so that it shares the unit of x."""
    return math.degrees(1.25 * math.log(math.tan(math.pi / 4 + 0.4 * math.radians(lat))))


TOP = miller(NORTH)
WIDTH = 360 * SCALE
HEIGHT = round((TOP - miller(SOUTH)) * SCALE)


def project(lon, lat):
    lat = max(min(lat, NORTH), SOUTH)
    return (lon + 180) * SCALE, (TOP - miller(lat)) * SCALE


def simplify(points, tolerance):
    """Douglas-Peucker on an open run of points."""
    if len(points) < 3:
        return points
    (x1, y1), (x2, y2) = points[0], points[-1]
    dx, dy = x2 - x1, y2 - y1
    length = math.hypot(dx, dy)
    far, index = -1.0, 0
    for i, (x, y) in enumerate(points[1:-1], 1):
        d = abs(dy * x - dx * y + x2 * y1 - y2 * x1) / length if length else math.hypot(x - x1, y - y1)
        if d > far:
            far, index = d, i
    if far <= tolerance:
        return [points[0], points[-1]]
    return simplify(points[: index + 1], tolerance)[:-1] + simplify(points[index:], tolerance)


def ring_path(ring):
    points = [project(lon, lat) for lon, lat in ring]
    # Split the closed ring in two so the simplification keeps both halves.
    half = len(points) // 2
    kept = simplify(points[: half + 1], TOLERANCE)[:-1] + simplify(points[half:], TOLERANCE)
    whole = []
    for x, y in kept:
        p = (round(x), round(y))
        if not whole or whole[-1] != p:
            whole.append(p)
    if len(whole) > 1 and whole[0] == whole[-1]:
        whole.pop()
    if len(whole) < 3:
        return ""
    steps = " ".join(f"{x - px} {y - py}" for (px, py), (x, y) in zip(whole, whole[1:]))
    return f"M{whole[0][0]} {whole[0][1]}l{steps}z"


def polygons(geometry):
    if geometry["type"] == "Polygon":
        return [geometry["coordinates"]]
    return geometry["coordinates"]


def main():
    with open(sys.argv[1]) as f:
        features = json.load(f)["features"]
    out = [
        '<?xml version="1.0" encoding="utf-8"?>',
        "<!-- Generated by tools/rv_stats_world.py from Natural Earth 1:110m Admin 0 countries v5.1.2 (public domain).",
        "     Regenerate rather than edit. The 節點分佈 card reads the paths and fills them in its own colours; Compose",
        "     draws them once, so the long paths do not cost a frame (VectorPath). -->",
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
        '    xmlns:tools="http://schemas.android.com/tools"',
        f'    android:width="{WIDTH // SCALE}dp"',
        f'    android:height="{HEIGHT // SCALE}dp"',
        f'    android:viewportWidth="{WIDTH}"',
        f'    android:viewportHeight="{HEIGHT}"',
        '    tools:ignore="VectorPath">',
    ]
    for feature in sorted(features, key=lambda f: f["properties"]["ISO_A2_EH"]):
        code = feature["properties"]["ISO_A2_EH"]
        if code in LEFT_OUT:
            continue
        data = "".join(ring_path(ring) for polygon in polygons(feature["geometry"]) for ring in polygon)
        if not data:
            continue
        name = f' android:name="{code}"' if code != "-99" else ""
        out.append(f'    <path{name} android:fillColor="#FFBDBDBD" android:fillType="evenOdd" android:pathData="{data}" />')
    out.append("</vector>")
    print("\n".join(out))


if __name__ == "__main__":
    main()
